// 스프라이트 그리기 함수
function drawSprite(spriteData, x, y, scale) {
    const s = scale || 1;
    for (let row = 0; row < spriteData.length; row++) {
        const line = spriteData[row];
        for (let col = 0; col < line.length; col++) {
            const ch = line[col];
            if (ch !== '0' && PALETTE[ch]) {
                ctx.fillStyle = PALETTE[ch];
                ctx.fillRect(
                    Math.floor(x + col * s),
                    Math.floor(y + row * s),
                    Math.ceil(s),
                    Math.ceil(s)
                );
            }
        }
    }
}
